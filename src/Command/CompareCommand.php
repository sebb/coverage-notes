<?php

declare(strict_types=1);

namespace Sebb\CoverageNotes\Command;

use Sebb\CoverageNotes\Coverage\CloverParser;
use Sebb\CoverageNotes\Diff\CoverageDiffer;
use Sebb\CoverageNotes\Git\BaselineResolutionStrategy;
use Sebb\CoverageNotes\Git\GitNotesStorage;
use Sebb\CoverageNotes\Report\ConsoleFormatter;
use Sebb\CoverageNotes\Report\JsonFormatter;
use Sebb\CoverageNotes\Report\MarkdownFormatter;
use Sebb\CoverageNotes\Report\ReportFormat;
use Symfony\Component\Console\Attribute\Argument;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Attribute\Option;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Output\ConsoleOutputInterface;
use Symfony\Component\Console\Output\OutputInterface;
use Throwable;

#[AsCommand(
    name: 'compare',
    description: 'Compare current Clover XML coverage against a baseline stored in Git notes.',
)]
final readonly class CompareCommand
{
    public function __construct(
        private CloverParser $parser = new CloverParser(),
        private CoverageDiffer $differ = new CoverageDiffer(),
        private ConsoleFormatter $consoleFormatter = new ConsoleFormatter(),
        private MarkdownFormatter $markdownFormatter = new MarkdownFormatter(),
        private JsonFormatter $jsonFormatter = new JsonFormatter(),
        private ?GitNotesStorage $storage = null,
    ) {
    }

    public function __invoke(
        OutputInterface $output,
        #[Argument(description: 'Path to the current Clover XML file generated by PHPUnit')]
        string $cloverFile = 'coverage.xml',
        #[Option(description: 'Base branch or commit reference to compare against', shortcut: 'b')]
        string $base = 'origin/main',
        #[Option(description: 'Baseline resolution strategy: "merge-base" or "direct"', shortcut: 's')]
        BaselineResolutionStrategy $strategy = BaselineResolutionStrategy::MergeBase,
        #[Option(description: 'Workspace root path to strip from relative file paths (defaults to current working directory)', shortcut: 'w')]
        ?string $workspace = null,
        #[Option(description: 'Git notes ref namespace (e.g. "coverage" for refs/notes/coverage)')]
        string $ref = GitNotesStorage::DEFAULT_NOTES_REF,
        #[Option(description: 'Git remote name for fetching notes')]
        string $remote = 'origin',
        #[Option(description: 'Fetch coverage notes from the remote before comparing')]
        bool $fetch = true,
        #[Option(description: 'Output format: "console", "markdown", or "json"', shortcut: 'f')]
        ReportFormat $format = ReportFormat::Console,
        #[Option(description: 'Fail (exit code 1) if overall project coverage percentage is below this threshold')]
        ?float $failUnder = null,
        #[Option(description: 'Fail (exit code 1) if overall coverage drops by more than this percentage compared to baseline')]
        ?float $maxDrop = null,
    ): int {
        $errorOutput = $output instanceof ConsoleOutputInterface ? $output->getErrorOutput() : $output;
        $effectiveWorkspace = $workspace ?? (getcwd() ?: null);

        try {
            $current = $this->parser->parseFile($cloverFile, $effectiveWorkspace);
        } catch (Throwable $e) {
            $errorOutput->writeln(sprintf('<error>%s</error>', $e->getMessage()));
            return Command::FAILURE;
        }

        $storage = $this->storage ?? new GitNotesStorage($effectiveWorkspace);

        if ($fetch) {
            $storage->fetchNotes($ref, $remote);
        }

        $resolvedBaseline = $storage->resolveBaseline($base, $strategy, $ref);
        $commitsBehind = $resolvedBaseline->commitsBehindTarget ?? 0;

        $diff = $this->differ->diff(
            current: $current,
            baseline: $resolvedBaseline?->summary,
            baselineCommit: $resolvedBaseline?->commitSha,
            commitsBehindTarget: $commitsBehind,
        );

        match ($format) {
            ReportFormat::Console => $this->consoleFormatter->render($diff, $output, $commitsBehind),
            ReportFormat::Markdown => $output->write($this->markdownFormatter->format($diff, $commitsBehind)),
            ReportFormat::Json => $output->write($this->jsonFormatter->format($diff)),
        };

        if ($failUnder !== null && $current->project->percentage < $failUnder) {
            $errorOutput->writeln(sprintf(
                '<error>Coverage (%.2f%%) is below the required minimum threshold of %.2f%%.</error>',
                $current->project->percentage,
                $failUnder,
            ));
            return Command::FAILURE;
        }

        if ($maxDrop !== null && $diff->projectPercentageDelta !== null) {
            $allowedDrop = abs($maxDrop);
            if ($diff->projectPercentageDelta < -$allowedDrop) {
                $errorOutput->writeln(sprintf(
                    '<error>Coverage dropped by %.2f%% (from %.2f%% to %.2f%%), which exceeds the maximum allowed drop of %.2f%%.</error>',
                    abs($diff->projectPercentageDelta),
                    $diff->baseline?->project->percentage ?? 0.0,
                    $current->project->percentage,
                    $allowedDrop,
                ));
                return Command::FAILURE;
            }
        }

        return Command::SUCCESS;
    }
}
