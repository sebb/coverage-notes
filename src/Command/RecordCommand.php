<?php

declare(strict_types=1);

namespace Sebb\CoverageNotes\Command;

use Sebb\CoverageNotes\Coverage\CloverParser;
use Sebb\CoverageNotes\Git\GitNotesStorage;
use Sebb\CoverageNotes\Serializer\CoverageSerializer;
use Symfony\Component\Console\Attribute\Argument;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Attribute\Option;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Output\OutputInterface;
use Throwable;

#[AsCommand(
    name: 'record',
    description: 'Parse a Clover XML coverage file and record a compact summary in Git notes.',
)]
final readonly class RecordCommand
{
    public function __construct(
        private CloverParser $parser = new CloverParser(),
        private CoverageSerializer $serializer = new CoverageSerializer(),
        private ?GitNotesStorage $storage = null,
    ) {
    }

    public function __invoke(
        OutputInterface $output,
        #[Argument(description: 'Path to the Clover XML file generated by PHPUnit')]
        string $cloverFile = 'coverage.xml',
        #[Option(description: 'Target commit reference to attach the coverage note to', shortcut: 'c')]
        string $commit = 'HEAD',
        #[Option(description: 'Workspace root path to strip from relative file paths (defaults to current working directory)', shortcut: 'w')]
        ?string $workspace = null,
        #[Option(description: 'Git notes ref namespace (e.g. "coverage" for refs/notes/coverage)')]
        string $ref = GitNotesStorage::DEFAULT_NOTES_REF,
        #[Option(description: 'Git remote name for fetching and pushing notes')]
        string $remote = 'origin',
        #[Option(description: 'Fetch existing coverage notes from the remote before recording')]
        bool $fetch = true,
        #[Option(description: 'Push the updated coverage notes ref to the remote repository', shortcut: 'p')]
        bool $push = false,
        #[Option(description: 'Print the generated JSON coverage note to stdout without writing to Git')]
        bool $dryRun = false,
    ): int {
        $effectiveWorkspace = $workspace ?? (getcwd() ?: null);

        try {
            $summary = $this->parser->parseFile($cloverFile, $effectiveWorkspace);
        } catch (Throwable $e) {
            $output->writeln(sprintf('<error>%s</error>', $e->getMessage()));
            return Command::FAILURE;
        }

        if ($dryRun) {
            $output->write($this->serializer->serializeSummary($summary));
            return Command::SUCCESS;
        }

        $storage = $this->storage ?? new GitNotesStorage($effectiveWorkspace, $this->serializer);

        try {
            if ($fetch) {
                $storage->fetchNotes($ref, $remote);
            }

            $sha = $storage->recordNote($summary, $commit, $ref);
            $output->writeln(sprintf(
                '<info>Recorded coverage note on commit</info> <comment>%s</comment> <info>(%.2f%%, %d/%d statements, %d items).</info>',
                substr($sha, 0, 7),
                $summary->project->percentage,
                $summary->project->covered,
                $summary->project->statements,
                count($summary->items),
            ));

            if ($push) {
                $storage->pushNotes($ref, $remote);
                $output->writeln(sprintf('<info>Pushed refs/notes/%s to %s.</info>', ltrim($ref, '/'), $remote));
            }
        } catch (Throwable $e) {
            $output->writeln(sprintf('<error>%s</error>', $e->getMessage()));
            return Command::FAILURE;
        }

        return Command::SUCCESS;
    }
}
